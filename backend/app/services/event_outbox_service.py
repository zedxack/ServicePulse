"""
ServicePulse - Event Outbox Service
Records transactional outbox events to bridge worker processes with WebSocket clients.
Author: Muhammadyusuf Usmonov
"""
import json
import logging
from datetime import datetime, timezone
from typing import Optional

from sqlalchemy.ext.asyncio import AsyncSession

from backend.app.models.event_outbox import RealtimeEvent

logger = logging.getLogger(__name__)


class EventOutboxService:
    """
    Transactional Outbox Publisher.
    Stores events generated by background workers directly in PostgreSQL so that
    FastAPI WebSocket processes can consume and dispatch them without external brokers.
    """

    @staticmethod
    async def record_worker_event(
        db: AsyncSession,
        organization_id: int,
        event_type: str,
        data: dict,
        target_role: Optional[str] = None,
    ) -> RealtimeEvent:
        """
        Record a real-time event into the PostgreSQL outbox within the existing db transaction.
        The backend Outbox Listener will read and dispatch this event to active WebSocket subscribers.
        """
        event = RealtimeEvent(
            organization_id=organization_id,
            event_type=event_type,
            payload=json.dumps(data),
            target_role=target_role,
            origin="worker",
            created_at=datetime.now(timezone.utc),
        )
        db.add(event)
        return event
